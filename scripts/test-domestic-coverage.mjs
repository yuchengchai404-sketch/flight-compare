import assert from 'node:assert/strict';
import {cities,mainlandCities,normalizeQuery,routeMatches,legQuery,airportAliases} from '../lib/flight-query.mjs';
import {resolvePlace} from '../lib/place-input.mjs';
import {providerSearchUrl,isDomesticQuery} from '../lib/provider-links.mjs';
import {apiDate} from '../lib/api-quotes.mjs';
import '../browser-helper/google-search-core.js';
const core=globalThis.flightProviderSearchCore,google=globalThis.flightGoogleSearchCore;
let count=0;
for(const from of mainlandCities)for(const to of mainlandCities){
 if(from===to)continue;
 const q=normalizeQuery({from,to,out:'2027-01-01',back:'2027-01-03',adults:1,cabin:'economy',tripType:'roundtrip'});
 assert.equal(resolvePlace(cities[from].name),from);assert.ok(isDomesticQuery(q));assert.ok(apiDate(q));
 for(const direction of ['outbound','return']){
  const l=legQuery(q,direction);
  for(const provider of ['ctrip','ly']){
   const url=providerSearchUrl(provider,q,direction);
   const meta=provider==='ctrip'?core.inspectCtripUrl(url):core.inspectLyDomesticUrl(url);
   assert.ok(meta,url);assert.equal(meta.from,l.from);assert.equal(meta.to,l.to);assert.equal(meta.date,l.date);
  }
  const meta=google.inspect(google.searchUrl(q,direction));assert.ok(meta);
  assert.ok(routeMatches(meta.from,l.from));assert.ok(routeMatches(meta.to,l.to));assert.equal(meta.date,l.date);assert.equal(meta.currency,'CNY');
 }
 count++;
}
// Real Google URL generated by selecting Guangzhou/Chengdu and nonstop on 2026-10-28.
const actual='https://www.google.com/travel/flights/search?tfs=CBwQAhorEgoyMDI3LTAxLTAxKABqDAgCEggvbS8wMzkzZ3INCAISCS9tLzAxNnY0NkABSAFwAYIBCwj___________8BmAEC&tfu=EgYIABAAGAA&hl=zh-CN&curr=CNY';
assert.equal(google.inspect(actual).from,'CAN');assert.equal(google.inspect(actual).to,'CTU');
assert.ok(routeMatches('TFU','CTU'));assert.ok(routeMatches('CTU','CTU'));assert.ok(!routeMatches('CAN','CTU'));
for(const [name,code] of Object.entries(airportAliases))assert.ok(core.airportText(name+'国际机场\n浦东国际机场').includes(code),name);
assert.equal(resolvePlace('广州白云机场'),'CAN');assert.throws(()=>resolvePlace('成都双流机场'),/整个城市/);
const q=normalizeQuery({from:'CAN',to:'CTU',out:'2027-01-01',back:'2027-01-03',adults:1,cabin:'economy'});
const ly=providerSearchUrl('ly',q);
for(const replacement of ['date=2027-02-30','date=2027-01-01&date=2027-01-02'])assert.equal(core.inspectLyDomesticUrl(ly.replace('date=2027-01-01',replacement)),null);
assert.equal(core.inspectLyDomesticUrl(ly.replace('CAN-CTU','CAN-HKG')),null);
assert.equal(providerSearchUrl('ly',{...q,adults:2}),'https://www.ly.com/flights/home');
console.log(`PASS: ${count} domestic city pairs, both directions, three provider link/condition guards; observed Google multi-airport URL; airport mapping and unsupported-query boundaries.`);
