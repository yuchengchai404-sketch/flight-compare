import assert from 'node:assert/strict';
import {normalizeQuote} from '../lib/quote-normalize.mjs';
const query={from:'SHA',to:'OSA',out:'2027-03-02',back:'2027-03-09',adults:1,cabin:'economy',tripType:'roundtrip'};
const input={query,source:'ly',direction:'outbound',tripType:'oneway',pageMeta:{verified:true,from:'SHA',to:'OSA',date:query.out,adults:1,cabin:'economy',tripType:'oneway',currency:'CNY'}};
const parse=label=>normalizeQuote({...input,text:`${label}\nPVG KIX 19:05 22:00\n经济舱\nCNY 1978 含税总价`});
const actual=parse('全日空\nNH976 空客A320（中）');
assert.equal(actual.eligible,true);
assert.equal(actual.legs[0].flight,'NH976');
assert.equal(actual.legs[0].direct,undefined,'missing nonstop evidence must remain unknown');
assert.equal(parse('山东航空\nSC4608 波音737-MAX8（中）').legs[0].flight,'SC4608');
assert.equal(parse('山东航空').legs[0].airline,'山东航空');
assert.equal(parse('香港航空').legs[0].airline,'香港航空');
assert.equal(parse('全日空\n国航').legs[0].airline,'全日空 / 国航');
assert.equal(parse('香港航空\nHX235 空客A320\nHX612 空客A320').legs[0].flight,undefined,'do not collapse a connection to one flight');
assert.equal(parse('A320').legs[0].flight,'A320','unprefixed identifiers are not presumed aircraft');
console.log('Airline labels and aircraft ambiguity checks passed');
assert.equal(parse('日航\n加航').legs[0].airline,'日航 / 加航');
assert.equal(parse('英航').legs[0].airline,'英航');
assert.equal(parse('达美航空').legs[0].airline,'达美航空');
assert.equal(parse('美联航').legs[0].airline,'美联航');
