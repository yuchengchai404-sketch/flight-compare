import assert from 'node:assert/strict';
import {domesticJob} from '../lib/domestic-job.mjs';
import {refreshProvider} from '../lib/refresh-provider.mjs';
const day={id:'SHA-BJS-test',out:'2027-01-01',back:'2027-01-03'};
const id='a0000000-0000-4000-8000-000000000001';
let clock=100000, calls=[];const states=new Map();
const base={day,from:'上海',to:'北京',now:()=>clock,newId:()=>id,read:async k=>states.get(k),write:async(k,v)=>states.set(k,v),queryLeg:async(date,from,to)=>{calls.push([date,from,to]);return [{flightNumber:'FM9103',type:'直飞',cabinClass:'经济舱',priceWithTax:520,departureTime:date+' 07:00',arrivalTime:date+' 09:00'}];}};
const start=await domesticJob(base);
assert.equal(start.pending,true);assert.equal(start.snapshot,undefined);assert.equal(calls.length,1);
const waiting=await domesticJob({...base,jobId:id});assert.equal(waiting.retryAfterMs,13000);assert.equal(calls.length,1);
await assert.rejects(domesticJob({...base,from:'广州',jobId:id}),/失效/);
await assert.rejects(domesticJob({...base,jobId:'../other'}),/无效/);
clock+=13000;
const done=await domesticJob({...base,jobId:id});assert.equal(done.snapshot.items[0].price,1040);
assert.deepEqual(calls,[[day.out,'上海','北京'],[day.back,'北京','上海']]);
assert.deepEqual(await domesticJob({...base,jobId:id}),done);assert.equal(calls.length,2);
clock+=600001;await assert.rejects(domesticJob({...base,jobId:id}),/失效/);
const query={id:'same-query'};let reads=0,waits=[];
const fetched=await refreshProvider(query,'tuniu',{read:async(_,opts)=>{const body=JSON.parse(opts.request.body);reads++;assert.deepEqual(body.query,query);if(reads===1){assert.equal(body.jobId,undefined);return start;}assert.equal(body.jobId,id);return done;},wait:async ms=>waits.push(ms)});
assert.equal(fetched.items[0].price,1040);assert.deepEqual(waits,[13000]);
let active=true;reads=0;
assert.equal(await refreshProvider(query,'tuniu',{active:()=>active,read:async()=>{reads++;return start;},wait:async()=>{active=false;}}),null);assert.equal(reads,1);
await assert.rejects(refreshProvider(query,'tuniu',{read:async()=>({pending:true,jobId:id,retryAfterMs:999999})}),/进度异常/);
await assert.rejects(refreshProvider(query,'tuniu',{read:async()=>{throw Error('网络失败');}}),/网络失败/);
const noFlights=await domesticJob({...base,queryLeg:async()=>[]});assert.equal(noFlights.pending,true);clock+=13000;const returnOnly=await domesticJob({...base,jobId:noFlights.jobId});assert.equal(returnOnly.snapshot.items.length,1);assert.equal(returnOnly.snapshot.items[0].direction,'return');
console.log('PASS: staged domestic queries preserve complete snapshots, exact query binding, rate spacing, expiry, replay, client cancellation and malformed progress.');
